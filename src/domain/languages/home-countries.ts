export function missingHomeCountries(code: string, listed: string[]): string[] | null {
  const home = HOME_COUNTRIES[code];
  if (!home || !listed.length) return null;
  return home.some((c) => listed.includes(c)) ? [] : home.slice(0, 1);
}
